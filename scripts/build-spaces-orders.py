#!/usr/bin/env python3
"""Build client/src/data/spacesOrders.generated.ts from Spaces_and_Product_Orders.xlsx.

Reads the sheets "Spaces" and "Product Orders". Formulas in the workbook are
recomputed here (area = length x width, order = area x (1 + waste)) so the
output does not depend on cached values. Nothing is invented: blank cells stay null.

Usage:
  python3 scripts/build-spaces-orders.py path/to/Spaces_and_Product_Orders.xlsx
  python3 scripts/build-spaces-orders.py path/to/file.xlsx --out client/src/data/spacesOrders.generated.ts

Source: OneDrive "Vic Point Reno/Spaces_and_Product_Orders.xlsx". Download it, then run the command above.
Requires: pip install openpyxl
"""

from __future__ import annotations

import argparse
import json
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "client" / "src" / "data" / "spacesOrders.generated.ts"
SECTIONS = {"Hybrid": "hybrid", "Carpet": "carpet", "Tiles": "tiles"}


def dec(v):
    if isinstance(v, bool) or v is None or isinstance(v, str) and not v.strip():
        return None
    if isinstance(v, (int, float)):
        return Decimal(str(v))
    if isinstance(v, str) and not v.startswith("="):
        try:
            return Decimal(v.replace(",", "").replace("$", ""))
        except Exception:
            return None
    return None


def r2(d):
    return None if d is None else float(d.quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def text(v):
    return None if v is None or str(v).startswith("=") or not str(v).strip() else str(v).strip()


def build(path: Path) -> dict:
    wb = openpyxl.load_workbook(path)
    ws = wb["Spaces"]
    rooms, totals_exact = [], {k: {"area": Decimal(0), "order": Decimal(0), "has_order": True} for k in SECTIONS.values()}
    for row in ws.iter_rows(min_row=2, values_only=True):
        name, section = text(row[0]), text(row[1])
        if section not in SECTIONS:
            continue
        key = SECTIONS[section]
        length, width, waste = dec(row[3]), dec(row[4]), dec(row[7])
        area = length * width if length is not None and width is not None else None
        order = area * (1 + waste) if area is not None and waste is not None else None
        if area is not None:
            totals_exact[key]["area"] += area
            if order is None:
                totals_exact[key]["has_order"] = False
            else:
                totals_exact[key]["order"] += order
        rooms.append({
            "room": name,
            "type": key,
            "floorType": text(row[2]),
            "length": None if length is None else float(length),
            "width": None if width is None else float(width),
            "area": r2(area),
            "rough": (text(row[6]) or "").lower().startswith("rough"),
            "measureQuality": text(row[6]),
            "wastePct": None if waste is None else float(waste),
            "orderArea": r2(order),
            "notes": text(row[9]),
        })
    totals = {}
    for key, t in totals_exact.items():
        has_area = t["area"] > 0
        totals[key] = {
            "area": r2(t["area"]) if has_area else None,
            "orderArea": r2(t["order"]) if has_area and t["has_order"] else None,
        }

    wo = wb["Product Orders"]
    spaces_by_key = {"Spaces!I10": totals["hybrid"]["orderArea"]}
    orders = []
    for row in wo.iter_rows(min_row=2, values_only=True):
        item = text(row[0])
        if not item:
            continue
        qty = dec(row[4])
        if qty is None and isinstance(row[4], str) and row[4].replace(" ", "").lstrip("=") in spaces_by_key:
            qty = spaces_by_key[row[4].replace(" ", "").lstrip("=")]
            qty = None if qty is None else Decimal(str(qty))
        unit_price, total = dec(row[8]), dec(row[9])
        orders.append({
            "item": item,
            "supplier": text(row[1]),
            "code": text(row[2]),
            "rooms": text(row[3]),
            "qty": None if qty is None else float(qty),
            "unit": text(row[5]),
            "unitPrice": r2(unit_price),
            "total": r2(total),
            "status": text(row[10]),
            "ref": text(row[11]),
            "notes": text(row[12]),
        })
    return {"rooms": rooms, "totals": totals, "orders": orders, "source": path.name}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("xlsx", type=Path)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()
    data = build(args.xlsx)
    body = json.dumps(data, indent=2, ensure_ascii=False)
    args.out.write_text(
        "// Generated by scripts/build-spaces-orders.py from Spaces_and_Product_Orders.xlsx.\n"
        "// Do not edit by hand. Change the spreadsheet, then rerun the script:\n"
        "//   python3 scripts/build-spaces-orders.py path/to/Spaces_and_Product_Orders.xlsx\n"
        "// Source file: OneDrive / Vic Point Reno / Spaces_and_Product_Orders.xlsx\n\n"
        "export type SpaceType = \"hybrid\" | \"carpet\" | \"tiles\";\n\n"
        "export interface SpaceRow {\n  room: string | null;\n  type: SpaceType;\n  floorType: string | null;\n"
        "  length: number | null;\n  width: number | null;\n  area: number | null;\n  rough: boolean;\n"
        "  measureQuality: string | null;\n  wastePct: number | null;\n  orderArea: number | null;\n  notes: string | null;\n}\n\n"
        "export interface ProductOrder {\n  item: string;\n  supplier: string | null;\n  code: string | null;\n  rooms: string | null;\n"
        "  qty: number | null;\n  unit: string | null;\n  unitPrice: number | null;\n  total: number | null;\n"
        "  status: string | null;\n  ref: string | null;\n  notes: string | null;\n}\n\n"
        f"export const SPACES_ORDERS: {{\n  rooms: SpaceRow[];\n  totals: Record<SpaceType, {{ area: number | null; orderArea: number | null }}>;\n  orders: ProductOrder[];\n  source: string;\n}} = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {args.out} ({len(data['rooms'])} rooms, {len(data['orders'])} orders)")
    print(json.dumps(data["totals"]))


if __name__ == "__main__":
    main()
